wnl = WordNetLemmatizer()

def preprocess(text):
  stop_words = set(stopwords.words('english'))
  stop_words.update(['.', ',', '!', '?', '*'])
  tokens = word_tokenize(text)
  tokens_lem = [wnl.lemmatize(token) for token in tokens]
  tokens_nosw = [token for token in tokens_lem if token.lower() not in stop_words]
  return ' '.join(tokens_nosw)

text_msg['processed_text'] = text_msg['merged_text'].apply(preprocess)

