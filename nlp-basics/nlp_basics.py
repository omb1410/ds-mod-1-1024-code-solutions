import pandas as pd

winemag = pd.read_csv('winemag-data.csv')
winemag

from nltk.tokenize import word_tokenize
import nltk
nltk.download('punkt_tab')

desc_token = winemag['description'].apply(word_tokenize)
desc_token

from nltk.corpus import stopwords
nltk.download('stopwords')

stop_words = set(stopwords.words('english'))

stop_words.update(['.', ',', '!', '?'])

desc_sw = []
for word_list in desc_token:
  for word in word_list:
    if word not in stop_words:
      desc_sw.append(word)

desc_sw

from nltk.stem import PorterStemmer, LancasterStemmer, SnowballStemmer

ps = PorterStemmer()
ls = LancasterStemmer()
ss = SnowballStemmer('english')

desc_stem = []
for sent in desc_sw:
  sent_stem = []
  for word in word_tokenize(sent):
    sent_stem.append(ps.stem(word))
  desc_stem.append(" ".join(sent_stem))

desc_stem

from nltk.stem import WordNetLemmatizer

nltk.download('wordnet')
wnl = WordNetLemmatizer()

desc_lemma = []
for sent in desc_stem:
  sent_lemma = []
  for word in sent.split():
    sent_lemma.append(wnl.lemmatize(word))
  desc_lemma.append(" ".join(sent_lemma))

desc_lemma

def stem_description(description):
  tokens = word_tokenize(description)
  tokens_stem = [ps.stem(token) for token in tokens]
  tokens_nosw = [token for token in tokens_stem if token.lower() not in stop_words]
  return ' '.join(tokens_nosw)

winemag['Cleaned_Stem_Description'] = winemag['description'].apply(stem_description)
winemag

def lem_description(description):
  tokens = word_tokenize(description)
  tokens_stem = [wnl.lemmatize(token) for token in tokens]
  tokens_nosw = [token for token in tokens_stem if token.lower() not in stop_words]
  return ' '.join(tokens_nosw)

winemag['Cleaned_Lemma_Description'] = winemag['description'].apply(lem_description)
winemag

from wordcloud import WordCloud

# Commented out IPython magic to ensure Python compatibility.
import matplotlib.pyplot as plt
# %matplotlib inline

text = ' '.join(description for description in winemag['Cleaned_Lemma_Description'])

word_cloud = WordCloud().generate(text)

plt.figure(figsize=(10, 8), facecolor=None)
plt.imshow(word_cloud)
plt.axis("off")
plt.tight_layout(pad=0)
plt.show()