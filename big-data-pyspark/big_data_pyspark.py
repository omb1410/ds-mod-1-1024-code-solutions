import pyspark
from pyspark.sql import SparkSession
from pyspark.sql.functions import col, when, count, mean, asc, desc
from pyspark.sql import functions as F

spark = SparkSession.builder.getOrCreate()

data = spark.read.csv('/content/LoansDataset.csv', header=True, inferSchema=True)
data

data.show()

data.printSchema()

data.count()

from pyspark.sql.functions import col, when

data = data.withColumn('Purpose', when(data['Purpose'] == 'other', 'Other').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'wedding', 'Wedding').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'small_business', 'Small Business').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'moving', 'Moving').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'vacation', 'Vacation').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'renewable_energy', 'Renewable Energy').otherwise(data['Purpose']))

data = data.withColumn('Purpose', when(data['Purpose'] == 'major_purchase', 'Major Purchase').otherwise(data['Purpose']))

data.select('Purpose').distinct().show()

data = data.withColumn('Home Ownership', when(data['Home Ownership'] == 'HaveMortgage', 'Home Mortgage').otherwise(data['Home Ownership']))

data.select('Home Ownership').distinct().show()

data.select('Number of Credit Problems').distinct().show()

data.select('Credit Score').distinct().show()

data = data.withColumn('Credit Score', when(data['Credit Score'] > 850, col('Credit Score')/10).otherwise(col('Credit Score')))

data.select('Credit Score').distinct().show()

from pyspark.sql.functions import count

data.groupBy("Loan ID").count().filter(col("count") > 1).show()

data = data.dropDuplicates(["Loan ID"])

data.show()

data.count()

mean_credit_score = data.select(mean("Credit Score")).collect()[0][0]

data = data.fillna({'Credit Score': mean_credit_score})

data = data.withColumn("Credit Score", col("Credit Score").cast("int"))

data.show()

median_income = data.approxQuantile('Annual Income', [0.5], 0.01)[0]

data = data.fillna({'Annual Income': median_income})

data.show()

data = data.fillna({'Months since last delinquent': 0})

data.show()

current_loan = data.filter(data['Current Loan Amount'] == 99999999)

current_loan.show()

data = data.withColumn('Current Loan Amount', when(data['Current Loan Amount'] == 99999999, 0).otherwise(data['Current Loan Amount']))

data.show()

data = data.withColumn('Credit Ultilization %', (col('Current Credit Balance')/col('Maximum Open Credit')) * 100)

data.show()

data = data.withColumn('Credit % of Annual Income', (col('Current Credit Balance')/col('Annual Income'))*100)

data.show()

