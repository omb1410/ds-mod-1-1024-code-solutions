import pandas as pd
import numpy as np

reviews = pd.read_json('Beauty.json', lines=True)
reviews

reviews['asin'].unique() #we have 85 different products

reviews['reviewerID'].unique()

ratings_grp = reviews.groupby('asin').agg({'overall': [np.size, np.sum, np.mean]})
ratings_grp

popular_products = ratings_grp[ratings_grp[('overall', 'size')] > 5].sort_values(('overall', 'mean'), ascending=False)
popular_products

def recommend_beauty_products(df, uid, n):
  reviewed = reviews.loc[reviews['reviewerID']==uid, 'asin']
  unreviewed = [title for title in reviews['asin'].unique() if title not in reviewed]
  return unreviewed[:n]

recommend_beauty_products(popular_products, 'A156IOMOA59X7N', 5)

"""## Next Items Purchased"""

ratings_sort = reviews.sort_values(by=['reviewerID', 'unixReviewTime'])
ratings_sort

ratings_sort.reset_index(inplace=True, drop=True)
reviews

ratings_sort['next'] = ratings_sort['asin'].shift(-1)
ratings_sort

ratings_sort[(ratings_sort['reviewerID']=='A105A034ZG9EHO') | (ratings_sort['reviewerID']=='AZRD4IZU6TBFV')]

for x in range(len(ratings_sort)-1):
  if ratings_sort['reviewerID'][x] == ratings_sort['reviewerID'][x+1]:
    ratings_sort['next'][x] = ratings_sort['asin'][x+1]

ratings_sort['next'].fillna(value=np.nan, inplace=True)

def rec_next(reviews, uid, n):
  last_product = reviews.loc[reviews['reviewerID']==uid, 'asin'].iloc[-1]
  print(f"Last Product: {last_product}")

  next_products = reviews.loc[reviews['asin']==last_product, 'next'].value_counts(dropna=True)[:n]
  print(f"Products Recommendation: {next_products}")

rec_next(ratings_sort, 'A156IOMOA59X7N', 5)

